import fs from "node:fs";
import vm from "node:vm";
import path from "node:path";
import { fileURLToPath } from "node:url";
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
globalThis.window = globalThis;
globalThis.self = globalThis;
vm.runInThisContext(fs.readFileSync(path.join(root, "src/core/parser-plugins.js"), "utf8"), { filename: "src/core/parser-plugins.js" });
vm.runInThisContext(fs.readFileSync(path.join(root, "src/core/parser.js"), "utf8"), { filename: "src/core/parser.js" });
const assert = (condition, message) => { if (!condition) throw new Error(message); };
assert(SignalDockParserPlugins.list().some((plugin) => plugin.id === "cef"), "bundled CEF plugin should be registered");
const cef = 'CEF:0|Acme|Gatekeeper|2.0|AUTH-7|Invalid token|9|rt=2026-09-12T20:00:00Z src=10.0.0.5 msg=signature failed';
const entry = SignalDockParser.parseText(cef, "security.log")[0];
assert(entry.service === "Gatekeeper", `expected CEF product as service, got ${entry.service}`);
assert(entry.level === "ERROR", `expected high CEF severity to map to ERROR, got ${entry.level}`);
assert(/Invalid token/.test(entry.message), `unexpected CEF message: ${entry.message}`);
SignalDockParserPlugins.register({ id: "demo-plugin", label: "Demo", priority: 200, test: (line) => line.startsWith("DEMO|"), parse: (line) => ({ service: "demo", level: "INFO", message: line.slice(5) }) });
const demo = SignalDockParser.parseText("DEMO|hello plugin", "demo.log")[0];
assert(demo.service === "demo" && demo.message === "hello plugin", "registered parser plugin should participate in auto parsing");
assert(SignalDockParserPlugins.unregister("demo-plugin"), "plugin unregister should succeed");
console.log("PASS parser plugin registry + bundled CEF parser");
