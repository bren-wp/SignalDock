import fs from "node:fs";
import vm from "node:vm";
import path from "node:path";
import { fileURLToPath } from "node:url";
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
globalThis.self = globalThis;
globalThis.window = globalThis;
vm.runInThisContext(fs.readFileSync(path.join(root, "virtual-viewport.js"), "utf8"), { filename: "virtual-viewport.js" });
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const million = SignalDockVirtualViewport.calculate({ total: 1_000_000, rowHeight: 46, viewportHeight: 700, scrollTop: 4_000_000, overscan: 24, maxScrollPx: 8_000_000 });
assert(million.compressed, "million-row viewport should use compressed scroll scale");
assert(million.pitch === 8, `expected 8px logical pitch, got ${million.pitch}`);
assert(million.end - million.start < 100, `viewport should keep a bounded DOM window, got ${million.end - million.start}`);
assert(million.topSpacerPx + million.bottomSpacerPx < 8_100_000, "compressed spacers should remain under browser-friendly scroll range");
const small = SignalDockVirtualViewport.calculate({ total: 1000, rowHeight: 46, viewportHeight: 700, scrollTop: 4600, overscan: 10, maxScrollPx: 8_000_000 });
assert(!small.compressed && small.pitch === 46, "normal datasets should retain physical row pitch");
assert(small.start === 90, `expected start 90, got ${small.start}`);
console.log("PASS million-row compressed viewport + normal viewport mapping");
